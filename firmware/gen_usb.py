"""Write firmware/build/gen/usb.c: Felucca's firmware/src/usb.c with the two USB name strings replaced.

Felucca's file names the device "Felucca" by "Hügelton Instruments". Those names are Hügelton Instruments' own,
and this firmware is not Felucca, so it names itself. Nothing else in the file changes; firmware/build.sh runs this
before every build and firmware/build_in.sh puts build/gen first on the include path.

The loader that runs during an update is Felucca's own, unmodified, and keeps its own name ("Felucca Update").
The product name must keep matching the installers' port filter (/fm-1|felucca|ota|.../ in Felucca's fm1ota.js).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "Felucca" / "firmware" / "src" / "usb.c"
OUT = ROOT / "firmware" / "build" / "gen" / "usb.c"
MANUFACTURER = "Deadlock Interactive"
PRODUCT = "FM-1 Doom"


def descriptor(name, text):
    """a USB string descriptor: length, type 3, then the text as UTF-16LE"""
    if not text.isascii() or not 0 < len(text) <= 60:
        raise SystemExit(f"gen_usb: {text!r}: plain ASCII, at most 60 characters")
    chars = ", ".join(f"'{c}', 0" for c in text)
    return f"static const uint8_t {name}[] = {{{2 + 2 * len(text)}, 3, {chars}}};"


def main():
    s = SRC.read_text(encoding="utf-8")
    # Felucca's definitions, as they stand in v1.1.5: each must be there exactly once, or this script needs a look
    old1 = re.compile(r"static const uint8_t STR1\[\] = \{42, 3, 'H', 0, 0xFC, 0, 'g'.*?\};", re.S)
    old2 = "static const uint8_t STR2[] = {16, 3, 'F', 0, 'e', 0, 'l', 0, 'u', 0, 'c', 0, 'c', 0, 'a', 0};"
    if len(old1.findall(s)) != 1 or s.count(old2) != 1:
        raise SystemExit("gen_usb: Felucca's usb.c does not hold the name strings as expected (Felucca changed? review this script)")
    if not re.search(r"fm-1", PRODUCT, re.I):
        raise SystemExit("gen_usb: the product name must contain 'FM-1': the installers find the device by its port name")
    s = old1.sub(lambda _: descriptor("STR1", MANUFACTURER), s).replace(old2, descriptor("STR2", PRODUCT))
    head = ("/* GENERATED by fm1-doom firmware/gen_usb.py from Felucca's firmware/src/usb.c: do not edit.\n"
            " * Changed from the original (2026-10): the USB manufacturer and product name strings (STR1, STR2). */\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != head + s:      # leave the time stamp alone when nothing changed
        OUT.write_text(head + s, encoding="utf-8")
    print(f"gen_usb: {OUT.relative_to(ROOT)}: manufacturer {MANUFACTURER!r}, product {PRODUCT!r}")


if __name__ == "__main__":
    sys.exit(main())
