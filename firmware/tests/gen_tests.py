"""Derive the loader-variant host tests from Felucca's tests/ldr_test.c (GPL-3.0-only, (C) 2026 Leo Kuroshita) by
checked text replacements, into firmware/build/tests/:

  ldr_test_ext.c   Felucca's test with ONE line changed: it drives the loader variant's core. Every check is
                   Felucca's. Passing it means the variant treats an ordinary package exactly as Felucca's loader.
  doom_ldr_test.c  the same fake host and simulated flash, with the checks for a package that also carries the
                   data region [0x93000, 0xE0000).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = (ROOT / "Felucca" / "tests" / "ldr_test.c").read_text()
OUT = ROOT / "firmware" / "build" / "tests"
OUT.mkdir(parents=True, exist_ok=True)


def derive(text, repl):
    for a, b in repl:
        if text.count(a) != 1:
            raise SystemExit(f"gen_tests: expected exactly one {a[:60]!r} in Felucca's ldr_test.c (it changed: review)")
        text = text.replace(a, b)
    return "/* GENERATED by fm1-doom firmware/tests/gen_tests.py from Felucca's tests/ldr_test.c: do not edit */\n" + text


INC = [('#include "../firmware/src/ota.c"', '#include "../../../Felucca/firmware/src/ota.c"'),
       ('#include "../firmware/loader/ldr_core.c"', '#include "../../../Felucca/build/doomldr/ldr_core.c"')]
(OUT / "ldr_test_ext.c").write_text(derive(SRC, INC))
(OUT / "doom_ldr_test.c").write_text(derive(SRC, INC + [
    # allowed windows of the variant with a long package: erase [0x4000, 0xFC000), program [0x4000, 0xE0000)
    ("if (off < 0x4000u || off >= 0xFC000u || (off & 0xFFFu) || (off >= 0x97000u && off < 0xE0000u)) bad_range++;",
     "if (off < 0x4000u || off >= 0xFC000u || (off & 0xFFFu)) bad_range++;\n"
     "    if (off >= 0xE0000u) rec_erases++;\n    if (off < 0x93000u) app_erases++;"),
    ("if (off < 0x4000u || off + n > 0x93000u || ((off & 0xFFu) + n) > 256u) bad_range++;",
     "if (off < 0x4000u || off + n > 0xE0000u || ((off & 0xFFu) + n) > 256u) bad_range++;"),
    ("static uint32_t flip_addr = 0xFFFFFFFFu, flip_seen, flip_on;",
     "static uint32_t rec_erases, app_erases;\nstatic uint32_t flip_addr = 0xFFFFFFFFu, flip_seen, flip_on;"),
    # the old firmware's store: a pattern in every sector, the record lookalike among it
    ("        memcpy(user, nor + 0xA0000, sizeof user);",
     "        for (i = 0x97000u; i < 0xE0000u; i += 0x1000u) nor[i + 5u] = (uint8_t)(i >> 12);   /* old store contents */\n"
     "        memcpy(user, nor + 0xA0000, sizeof user);"),
    ("!memcmp(nor + 0x4000, old + ofo + 0x4000, 0x93000 - 0x4000) && nor[0xE4F06] == 0x41);",
     "!memcmp(nor + 0x4000, old + ofo + 0x4000, 0x93000 - 0x4000) && nor[0xE4F06] == 0x41 &&\n"
     "                     !memcmp(nor + 0xA0000, user, sizeof user));\n        app_erases = 0;"),
    ('    bad += check("app area == the new package\'s flash.bin", !memcmp(nor + 0x4000, logical + nfo + 0x4000, 0x93000 - 0x4000));',
     '    bad += check("app area == the new package\'s flash.bin", !memcmp(nor + 0x4000, logical + nfo + 0x4000, 0x93000 - 0x4000));\n'
     '    bad += check("data region [0x93000, 0xE0000) == the new package\'s flash.bin", !memcmp(nor + 0x93000, logical + nfo + 0x93000, 0xE0000 - 0x93000));\n'
     '    bad += check("nothing above 0xE0000 touched except the two update records", rec_erases == 2 && nor[0xFC000] == 0xFF);\n'
     '    printf("  %u sector erases in the app area\\n", app_erases);\n'
     '    if (argc > 3) bad += check("app area already equal: not one of its sectors erased", app_erases == 0);'),
    ('    bad += check("user data in Felucca\'s store that looks like a record is kept", !memcmp(nor + 0xA0000, user, sizeof user));',
     '    bad += check("the old store contents are gone (replaced by game data)", memcmp(nor + 0xA0000, user, sizeof user) != 0);'),
]))
print("gen_tests:", OUT)
